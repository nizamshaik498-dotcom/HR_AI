function sanitizeFilename(name) {
  return name.replace(/[^a-z0-9_.-]/gi, '_').slice(0, 100);
}

function escapeHtml(text) {
  const div = document.createElement('div');
  div.textContent = text;
  return div.innerHTML;
}

export function exportJSON(data, filename = 'interview-results.json') {
  try {
    const safeFilename = sanitizeFilename(filename);
    const blob = new Blob([JSON.stringify(data, null, 2)], { type: 'application/json' });
    downloadBlob(blob, safeFilename);
  } catch (e) {
    console.error('Export JSON failed:', e);
  }
}

export function exportTXT(data, filename = 'interview-report.txt') {
  try {
    const safeFilename = sanitizeFilename(filename);
    const lines = [
      'HR_AI Interview Report',
      '======================',
      '',
      `Category: ${escapeHtml(data.category || 'Unknown')}`,
      `Date: ${data.timestamp ? new Date(data.timestamp).toLocaleString() : 'Unknown'}`,
      `Duration: ${formatDuration(data.totalTime || 0)}`,
      `Questions: ${data.totalQuestions || 0}`,
      `Final Score: ${data.finalScore || 0}%`,
      `Average Score: ${data.avgScore || 0}%`,
      `Best Score: ${data.bestScore || 0}%`,
      '',
      'QUESTION BREAKDOWN',
      '------------------',
      ...(data.breakdown || []).map((q, i) => [
        `${i + 1}. ${escapeHtml(q.question || '')}`,
        `   Score: ${q.score || 0}% (${escapeHtml(q.grade || '')})`,
        `   Time: ${formatDuration(q.timeSpent || 0)}`,
        `   Key Points: ${(q.matched || []).length} matched, ${(q.missed || []).length} missed`,
        ''
      ]).flat(),
      'STRENGTHS',
      '---------',
      ...((data.strengths || []).length ? data.strengths.map(s => `• ${escapeHtml(s)}`) : ['• None identified']),
      '',
      'AREAS TO IMPROVE',
      '----------------',
      ...((data.improvements || []).length ? data.improvements.map(s => `• ${escapeHtml(s)}`) : ['• None identified']),
      '',
      'Generated by HR_AI Interview Simulator'
    ];

    const blob = new Blob([lines.join('\n')], { type: 'text/plain' });
    downloadBlob(blob, safeFilename);
  } catch (e) {
    console.error('Export TXT failed:', e);
  }
}

function downloadBlob(blob, filename) {
  try {
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    a.style.display = 'none';
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  } catch (e) {
    console.error('Download failed:', e);
  }
}

function formatDuration(seconds) {
  const secs = Math.max(0, Math.floor(seconds));
  const m = Math.floor(secs / 60);
  const s = secs % 60;
  return `${m}m ${s}s`;
}

export function generateReportData(session) {
  try {
    if (!session || !session.answers?.length) {
      return {
        category: session?.category || 'Unknown',
        timestamp: session?.startTime || Date.now(),
        totalTime: 0,
        totalQuestions: 0,
        finalScore: 0,
        avgScore: 0,
        bestScore: 0,
        breakdown: [],
        strengths: [],
        improvements: []
      };
    }

    const scores = session.answers.map(a => a.score || 0);
    const totalTime = session.answers.reduce((sum, a) => sum + (a.timeSpent || 0), 0);

    return {
      category: session.category || 'Unknown',
      timestamp: session.startTime || Date.now(),
      totalTime,
      totalQuestions: session.answers.length,
      finalScore: scores.length ? Math.round(scores.reduce((a, b) => a + b, 0) / scores.length) : 0,
      avgScore: scores.length ? Math.round(scores.reduce((a, b) => a + b, 0) / scores.length) : 0,
      bestScore: scores.length ? Math.max(...scores) : 0,
      breakdown: session.answers.map(a => ({
        question: a.question || '',
        score: a.score || 0,
        grade: a.grade || 'Needs Improvement',
        timeSpent: a.timeSpent || 0,
        matched: a.matched || [],
        missed: a.missed || []
      })),
      strengths: session.insights?.strengths || [],
      improvements: session.insights?.improvements || []
    };
  } catch (e) {
    console.error('Generate report data failed:', e);
    return {
      category: 'Error',
      timestamp: Date.now(),
      totalTime: 0,
      totalQuestions: 0,
      finalScore: 0,
      avgScore: 0,
      bestScore: 0,
      breakdown: [],
      strengths: [],
      improvements: []
    };
  }
}